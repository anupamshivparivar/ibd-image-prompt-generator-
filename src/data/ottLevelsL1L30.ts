export function getLoraTagForSubject(subject: string, levelCode: string): string {
  const s = (subject || "Deity").toLowerCase();
  if (s.includes("radha") && s.includes("krishna")) {
    return `Radha_${levelCode} + Krishna_${levelCode}`;
  }
  if (s.includes("siya") || (s.includes("ram") && s.includes("sita"))) {
    return `ShriRam_${levelCode} + MaaSita_${levelCode}`;
  }
  if (s.includes("vishnu") && s.includes("lakshmi")) {
    return `Vishnu_${levelCode} + Mahalakshmi_${levelCode}`;
  }
  if (s.includes("hanuman") && s.includes("ram")) {
    return `Hanuman_${levelCode} + ShriRam_${levelCode}`;
  }
  if (s.includes("hanuman")) return `Hanuman_${levelCode}`;
  if (s.includes("shiva") || s.includes("mahadev")) return `Mahadev_${levelCode}`;
  if (s.includes("krishna")) return `ShriKrishna_${levelCode}`;
  if (s.includes("ram")) return `ShriRam_${levelCode}`;
  if (s.includes("ganesh")) return `Ganesha_${levelCode}`;
  if (s.includes("durga") || s.includes("mata")) return `MaaDurga_${levelCode}`;
  if (s.includes("saraswati")) return `MaaSaraswati_${levelCode}`;
  const clean = (subject || "Divine")
    .replace(/[^a-zA-Z0-9]+/g, "")
    .slice(0, 18) || "Divine";
  return `${clean}_${levelCode}`;
}
